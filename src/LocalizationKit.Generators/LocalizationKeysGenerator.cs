using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace LocalizationKit.Generators;

/// <summary>Generates a constant for every resource key, so a key can be a compile error.</summary>
/// <remarks>
/// <para>
/// A localization key is a string, and a mistyped or deleted string is found by a user rather than by
/// the compiler. This reads the default culture's <c>.resw</c> and emits
/// <c>LocalizationKeys.Settings.Theme.Header</c> for a key named <c>Settings.Theme.Header</c>, which
/// a rename or a deletion then breaks the build over.
/// </para>
/// <para>
/// It reads the <em>default</em> culture only, on purpose: that file is the list of keys the
/// application has, and a translation is allowed to be behind. A key that exists only in a
/// translation is a finding for the validator (LK007), not a constant to offer.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class LocalizationKeysGenerator : IIncrementalGenerator
{
    private const string EnabledProperty = "build_property.LocalizationKitGenerateKeys";
    private const string ClassNameProperty = "build_property.LocalizationKitKeysClass";
    private const string NamespaceProperty = "build_property.LocalizationKitKeysNamespace";
    private const string AccessibilityProperty = "build_property.LocalizationKitKeysAccessibility";
    private const string RootNamespaceProperty = "build_property.RootNamespace";
    private const string ResourceMetadata = "build_metadata.AdditionalFiles.LocalizationKitKeys";

    private static readonly DiagnosticDescriptor CouldNotRead = new DiagnosticDescriptor(
        id: "LKG001",
        title: "A resource file could not be read",
        messageFormat: "'{0}' could not be read as a .resw file, so no keys were generated from it: {1}",
        category: "LocalizationKit",
        defaultSeverity: DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The options an application sets, and the one list of keys worth generating from. Both are
        // tracked separately so that editing a resource file does not re-read the options and vice
        // versa; that is the difference between an incremental generator and a generator.
        IncrementalValueProvider<Settings> settings = context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) => Settings.From(options.GlobalOptions));

        IncrementalValuesProvider<ResourceFile> files = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Where(static pair => IsResourceFile(pair.Right.GetOptions(pair.Left)))
            .Select(static (pair, cancellationToken) => ResourceFile.Read(pair.Left, cancellationToken));

        context.RegisterSourceOutput(
            files.Collect().Combine(settings),
            static (production, source) => Emit(production, source.Left, source.Right));
    }

    private static bool IsResourceFile(AnalyzerConfigOptions options)
    {
        return options.TryGetValue(ResourceMetadata, out string? value)
            && value.Equals("true", StringComparison.OrdinalIgnoreCase);
    }

    private static void Emit(
        SourceProductionContext context,
        ImmutableArray<ResourceFile> files,
        Settings settings)
    {
        if (!settings.Enabled)
        {
            return;
        }

        foreach (ResourceFile file in files)
        {
            if (file.Error is { } error)
            {
                context.ReportDiagnostic(Diagnostic.Create(CouldNotRead, Location.None, file.Path, error));
            }
        }

        // CreateRange rather than a collection expression: the System.Collections.Immutable an
        // analyzer compiles against is too old for those.
        ImmutableArray<string> keys = ImmutableArray.CreateRange(files
            .SelectMany(static file => file.Keys)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static key => key, StringComparer.Ordinal));

        if (keys.Length == 0)
        {
            // Nothing to say, and an empty class is worse than no class: it would compile, and every
            // call site using it would then fail with a less obvious error.
            return;
        }

        KeyTree tree = new KeyTree();
        foreach (string key in keys)
        {
            tree.Add(key);
        }

        StringBuilder builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        string indent = string.Empty;

        if (settings.Namespace is { Length: > 0 } @namespace)
        {
            builder.Append("namespace ").Append(@namespace).AppendLine(";");
            builder.AppendLine();
        }

        builder.Append("/// <summary>The resource keys this project ships, as constants.</summary>")
            .AppendLine();
        builder.Append("/// <remarks>Generated from the default culture's resource file by ")
            .AppendLine("LocalizationKit.</remarks>");
        builder.Append(indent).Append(settings.Accessibility).Append(" static partial class ")
            .AppendLine(settings.ClassName);
        builder.AppendLine("{");
        tree.Write(builder, "    ");
        builder.AppendLine("}");

        context.AddSource(settings.ClassName + ".g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }

    private sealed record Settings(bool Enabled, string ClassName, string? Namespace, string Accessibility)
    {
        public static Settings From(AnalyzerConfigOptions options)
        {
            bool enabled = !options.TryGetValue(EnabledProperty, out string? value)
                || !value.Equals("false", StringComparison.OrdinalIgnoreCase);

            options.TryGetValue(ClassNameProperty, out string? className);
            options.TryGetValue(NamespaceProperty, out string? @namespace);
            options.TryGetValue(AccessibilityProperty, out string? accessibility);
            options.TryGetValue(RootNamespaceProperty, out string? rootNamespace);

            return new Settings(
                enabled,
                string.IsNullOrWhiteSpace(className) ? "LocalizationKeys" : className!.Trim(),
                string.IsNullOrWhiteSpace(@namespace) ? rootNamespace?.Trim() : @namespace!.Trim(),

                // Internal by default: keys are an implementation detail of the project that owns the
                // resources, and a public surface is something to opt into rather than inherit.
                string.Equals(accessibility?.Trim(), "public", StringComparison.OrdinalIgnoreCase)
                    ? "public"
                    : "internal");
        }
    }

    private sealed record ResourceFile(string Path, ImmutableArray<string> Keys, string? Error)
    {
        public static ResourceFile Read(AdditionalText text, CancellationToken cancellationToken)
        {
            SourceText? content = text.GetText(cancellationToken);

            if (content is null)
            {
                return new ResourceFile(
                    text.Path,
                    ImmutableArray<string>.Empty,
                    "the file could not be opened");
            }

            try
            {
                XDocument document = XDocument.Parse(content.ToString());

                IEnumerable<string> names = document.Root?.Elements("data")
                    .Where(static data => data.Attribute("type") is null
                        && data.Attribute("mimetype") is null)
                    .Select(static data => data.Attribute("name")?.Value)
                    .Where(static name => !string.IsNullOrEmpty(name))
                    .Select(static name => name!)
                    ?? Enumerable.Empty<string>();

                return new ResourceFile(text.Path, ImmutableArray.CreateRange(names), null);
            }
            catch (XmlException exception)
            {
                return new ResourceFile(text.Path, ImmutableArray<string>.Empty, exception.Message);
            }
        }
    }
}
